import assert from "node:assert/strict";
import { createServer } from "node:http";
import { once } from "node:events";
import { copyFile, mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { DEFAULT_SETTINGS } from "../src/shared/types";
import { PluginPackageStore } from "../src/main/services/plugin-packages";
import { startPluginMcp } from "../src/main/services/plugin-mcp";
import { ensureNovaCodexHome } from "../src/main/services/nova-runtime";
import { prepareLocalProvider, providerArguments, resolveExecutable, runProvider } from "../src/main/services/providers";

test("installed Codex exposes a 474-tool imported plugin to a synthetic local model", { skip: process.env.NOVA_PLUGIN_LARGE_NATIVE_TEST !== "1", timeout: 60000 }, async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "nova-plugin-codex-"));
  const source = path.join(root, "source"); await mkdir(source);
  await copyFile(path.resolve("test/fixtures/mcp-server.mjs"), path.join(source, "server.mjs"));
  await writeFile(path.join(source, ".mcp.json"), JSON.stringify({ mcpServers: { fixture: { command: process.execPath, args: ["${CODEX_PLUGIN_ROOT}/server.mjs", "many"] } } }));
  const store = new PluginPackageStore(path.join(root, "data"));
  const preview = await store.preview(source); const pkg = await store.install(source, preview.fingerprint); await store.setEnabled(pkg.id, true);
  const copies = await store.prepareRun();
  const controller = new AbortController(); const approvals: string[] = [];
  const plugin = await startPluginMcp(copies.packages, async (request) => { approvals.push(request.action); return true; }, controller.signal);
  t.after(async () => { await plugin.dispose(); await copies.dispose(); await rm(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }); });
  let count = 0, exposed = false, resultReceived = false, toolCount = 0;
  const server = createServer(async (req, res) => {
    if (req.url === "/v1/models") { res.writeHead(200, { "Content-Type": "application/json" }); res.end(JSON.stringify({ data: [{ id: "fixture-model" }] })); return; }
    let text = ""; for await (const chunk of req) text += chunk;
    const input = JSON.parse(text); const tool = input.tools?.find((entry: any) => /nova_plugins/i.test(entry.function?.name ?? ""));
    exposed ||= !!tool;
    toolCount = Math.max(toolCount, (input.tools ?? []).filter((entry: any) => /nova_plugins/i.test(entry.function?.name ?? "")).length);
    resultReceived ||= input.messages?.some((item: any) => item.role === "tool" && String(item.content).includes("server request denied"));
    res.writeHead(200, { "Content-Type": "text/event-stream" });
    if (++count === 1 && tool) res.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { tool_calls: [{ index: 0, id: "fixture-call", type: "function", function: { name: tool.function.name, arguments: JSON.stringify({ message: "synthetic" }) } }] }, finish_reason: "tool_calls" }] })}\n\n`);
    else res.write(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { content: "Fixture complete." }, finish_reason: "stop" }] })}\n\n`);
    res.end("data: [DONE]\n\n");
  });
  server.listen(0, "127.0.0.1"); await once(server, "listening");
  t.after(async () => { const done = new Promise<void>((resolve) => server.close(() => resolve())); server.closeAllConnections(); await done; });
  const address = server.address(); assert.ok(address && typeof address !== "string");
  const settings = { ...DEFAULT_SETTINGS, localProvider: "custom" as const, localProtocol: "chat-completions" as const, localBaseUrl: `http://127.0.0.1:${address.port}/v1`, localModel: "fixture-model" };
  const local = await prepareLocalProvider(settings, "fixture-model", controller.signal); t.after(local.dispose);
  const home = await ensureNovaCodexHome(path.join(root, "data")); const executable = await resolveExecutable("codex");
  const result = await runProvider({ command: { ...executable, env: { ...executable.env, ...local.env, CODEX_HOME: home, NOVA_PLUGIN_TOKEN: plugin.token }, args: providerArguments("ollama", root, "plan", "fixture-model", { allowNonGit: true, localConfigArgs: local.configArgs, pluginMcpUrl: plugin.url, pluginDirectory: copies.directory }) }, provider: "ollama", cwd: root, prompt: "Use the synthetic plugin.", signal: controller.signal, timeoutMs: 45000, maxBytes: 1024 * 1024, allowPluginImages: true, onEvent: () => {} });
  assert.equal(result.error, undefined);
  assert.equal(result.completed, true);
  assert.equal(exposed, true);
  assert.equal(toolCount, 474);
  assert.equal(resultReceived, true);
  assert.deepEqual(approvals, ["start", "discover", "call"]);
});
